CREATE TABLE roles (
  role_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       VARCHAR2(32)  NOT NULL UNIQUE,
  label_es   VARCHAR2(128) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE universities (
  university_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(256) NOT NULL UNIQUE,
  country       VARCHAR2(64)  DEFAULT 'España'
);

CREATE TABLE users (
  user_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email             VARCHAR2(256) NOT NULL UNIQUE,
  full_name         VARCHAR2(256) NOT NULL,
  university_id     NUMBER REFERENCES universities(university_id),
  password_hash     VARCHAR2(256) NOT NULL,
  password_salt     VARCHAR2(64)  NOT NULL,
  avatar_blob       BLOB,
  mimetype          VARCHAR2(64),
  filename          VARCHAR2(256),
  bio               VARCHAR2(1000),
  github_url        VARCHAR2(256),
  linkedin_url      VARCHAR2(256),
  theme_preference  VARCHAR2(16) DEFAULT 'light',
  active            CHAR(1) DEFAULT 'Y' CHECK (active IN ('Y','N')),
  created_at        TIMESTAMP DEFAULT SYSTIMESTAMP,
  updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE user_roles (
  user_id NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  role_id NUMBER NOT NULL REFERENCES roles(role_id),
  PRIMARY KEY (user_id, role_id)
);

-- Seguridad y auditoría
