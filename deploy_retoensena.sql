  log_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER REFERENCES users(user_id),
  attempt_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
  success     CHAR(1) CHECK (success IN ('Y','N')),
  ip_address  VARCHAR2(45),
  user_agent  VARCHAR2(512)
);

CREATE TABLE password_resets (
  reset_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     NUMBER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
  token       VARCHAR2(64) NOT NULL UNIQUE,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP,
  expires_at  TIMESTAMP NOT NULL,
  used_at     TIMESTAMP,
  ip_address  VARCHAR2(45),
  user_agent  VARCHAR2(512)
);

CREATE INDEX idx_password_resets_user    ON password_resets(user_id);
CREATE INDEX idx_password_resets_expires ON password_resets(expires_at);

