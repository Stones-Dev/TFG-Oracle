CREATE OR REPLACE PACKAGE pkg_auth AS
  FUNCTION generate_salt RETURN VARCHAR2;
  FUNCTION hash_password(p_password IN VARCHAR2, p_salt IN VARCHAR2) RETURN VARCHAR2;
  PROCEDURE register_user(
    p_email     IN VARCHAR2,
    p_full_name IN VARCHAR2,
    p_password  IN VARCHAR2,
    p_role_code IN VARCHAR2 DEFAULT 'PARTICIPANT',
    p_user_id   OUT NUMBER
  );
  FUNCTION authenticate(p_email IN VARCHAR2, p_password IN VARCHAR2) RETURN NUMBER;
END pkg_auth;
/

CREATE OR REPLACE PACKAGE BODY pkg_auth AS
  FUNCTION generate_salt RETURN VARCHAR2 IS
  BEGIN
    RETURN RAWTOHEX(DBMS_CRYPTO.RANDOMBYTES(16));
  END;

  FUNCTION hash_password(p_password IN VARCHAR2, p_salt IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN TO_CHAR(ORA_HASH(p_password || p_salt));
  END;

  PROCEDURE register_user(
    p_email     IN VARCHAR2,
    p_full_name IN VARCHAR2,
    p_password  IN VARCHAR2,
    p_role_code IN VARCHAR2 DEFAULT 'PARTICIPANT',
    p_user_id   OUT NUMBER
  ) IS
    v_salt VARCHAR2(64);
    v_hash VARCHAR2(256);
    v_role_id NUMBER;
  BEGIN
    v_salt := generate_salt();
    v_hash := hash_password(p_password, v_salt);
    INSERT INTO users(email, full_name, password_hash, password_salt)
      VALUES (LOWER(p_email), p_full_name, v_hash, v_salt)
      RETURNING user_id INTO p_user_id;
    SELECT role_id INTO v_role_id FROM roles WHERE code = p_role_code;
    INSERT INTO user_roles(user_id, role_id) VALUES (p_user_id, v_role_id);
  END;

  FUNCTION authenticate(p_email IN VARCHAR2, p_password IN VARCHAR2) RETURN NUMBER IS
    v_user_id NUMBER;
    v_hash    VARCHAR2(256);
    v_salt    VARCHAR2(64);
  BEGIN
    SELECT user_id, password_hash, password_salt
      INTO v_user_id, v_hash, v_salt
      FROM users
      WHERE LOWER(email) = LOWER(p_email) AND active = 'Y';
    IF v_hash = hash_password(p_password, v_salt) THEN
      RETURN v_user_id;
    ELSE
      RETURN NULL;
    END IF;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
  END;
END pkg_auth;
/

